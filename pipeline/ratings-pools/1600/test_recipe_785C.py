def official_pairs():
    return [(f'{i:04d}', {'input': n + '\r\n', 'output': a + '\r\n'}) for i, (n, a) in enumerate(OFFICIAL, 1)]


def tri(k):
    return k * (k + 1) // 2


def least_k(rest):
    k = 0
    while tri(k) < rest:
        k += 1
    return k


def wa_207785393(n, m):
    if m >= n:
        return n
    d = 1 + 8 * (n - m)
    return math.ceil((-1 + math.sqrt(d)) / 2) + m


def wa_212028901(n, m):
    if m >= n:
        return m + 1
    return recipe.closed_form((n, m))


def wa_212034643(n, m):
    if m >= n:
        return m + 1
    i = m + int(math.sqrt(2 * n)) - 2
    n = n - i + m
    i += 1
    return i if i == n else i + 1


def tle_212027059_logic(n, m):
    k, i = n, 1
    while m > i:
        i += 1
    while k > 0:
        k = n if k + m >= n else k + m
        k -= i
        i += 1
    return i - 1


def strict_threshold(n, m):
    if m >= n:
        return n
    lo, hi = 0, 2 * 10**9
    while lo < hi:
        mid = (lo + hi) // 2
        if tri(mid) > n - m:
            hi = mid
        else:
            lo = mid + 1
    return m + lo


def small_search_bound(n, m):
    if m >= n:
        return n
    lo, hi = 1, 10**9
    while lo < hi:
        mid = (lo + hi) // 2
        if tri(mid) >= n - m:
            hi = mid
        else:
            lo = mid + 1
    return m + lo


def wrap64(x):
    x &= (1 << 64) - 1
    return x - (1 << 64) if x >> 63 else x


def overflow_wide_bound(n, m):
    if m >= n:
        return n
    lo, hi = 1, LIMIT
    while lo < hi:
        mid = (lo + hi) // 2
        if wrap64(mid * (mid + 1)) // 2 >= n - m:
            hi = mid
        else:
            lo = mid + 1
    return m + lo


def answer_m_when_m_ge_n(n, m):
    return m if m >= n else recipe.closed_form((n, m))


class Recipe785CTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.cases = recipe.extras('785C')
        cls.parsed = [recipe.parse('785C', c['input']) for c in cls.cases]

    def test_parse_layout_and_range(self):
        self.assertEqual(recipe.parse('785C', '5 2'), (5, 2))
        self.assertEqual(recipe.parse('785C', '5 2\n'), (5, 2))
        self.assertEqual(recipe.parse('785C', '1000000000000000000 1\r\n'), (LIMIT, 1))
        bad = ['', '\n', '5', '5 2 1', '5\n2\n', '5  2', ' 5 2', '5 2 ', '5\t2', '0 1', '1 0',
               '1000000000000000001 1', '1 1000000000000000001', '-1 2', '+5 2', '05 2', '5 1_0',
               '5 2\n\n', '5 2\r\n\r\n', '5 2\r', '5.0 2']
        for text in bad:
            with self.subTest(text=text), self.assertRaises(ValueError):
                recipe.parse('785C', text)
        with self.assertRaises(ValueError):
            recipe.parse('1A', '5 2')

    def test_official_and_samples_agree_with_oracle_and_independent_checks(self):
        self.assertEqual(len(OFFICIAL), 223)
        samples = [(f'sample-{i}', {'input': a, 'output': b}) for i, (a, b) in enumerate(SAMPLES, 1)]
        self.assertEqual(recipe.review('785C', official_pairs(), samples), [])
        simulated = 0
        for text, out in OFFICIAL + SAMPLES:
            n, m = recipe.parse('785C', text)
            self.assertEqual(recipe.closed_form((n, m)), int(out))
            if m < n:
                k = int(out) - m
                self.assertTrue(tri(k) >= n - m > tri(k - 1))
            else:
                self.assertEqual(int(out), n)
            if int(out) <= 200000:
                self.assertEqual(recipe.brute('785C', (n, m)), int(out))
                simulated += 1
        self.assertGreater(simulated, 10)

    def test_review_reports_disagreement_and_malformed(self):
        failures = recipe.review('785C', [('x', {'input': '5 2\r\n', 'output': '5\r\n'}),
                                          ('y', {'input': '0 2\n', 'output': '1\n'}),
                                          ('z', {'input': '5\n2\n', 'output': '4\n'})], [])
        self.assertEqual([f['test'] for f in failures], ['x', 'y', 'z'])
        self.assertEqual(failures[0]['expected'], ['4'])

    def test_selected_wrong_sources_fail_at_recorded_test(self):
        tests = [tuple(map(int, t.split())) for t, _ in OFFICIAL]
        outs = [int(o) for _, o in OFFICIAL]
        for fn, passed in ((wa_207785393, 15), (wa_212028901, 3), (wa_212034643, 2)):
            with self.subTest(fn=fn.__name__):
                for (n, m), out in zip(tests[:passed], outs[:passed]):
                    self.assertEqual(fn(n, m), out)
                n, m = tests[passed]
                self.assertNotEqual(fn(n, m), outs[passed])

    def test_extras_kill_wrong_ideas(self):
        killers = {}
        mutants = (wa_207785393, wa_212028901, wa_212034643, strict_threshold, small_search_bound,
                   overflow_wide_bound, answer_m_when_m_ge_n)
        for fn in mutants:
            killers[fn.__name__] = sum(fn(n, m) != int(c['output']) for (n, m), c in zip(self.parsed, self.cases))
        small = [(d, c) for d, c in zip(self.parsed, self.cases) if int(c['output']) <= 5000 and d[1] <= 5000]
        killers['tle_212027059_logic'] = sum(tle_212027059_logic(*d) != int(c['output']) for d, c in small)
        for name, kills in killers.items():
            with self.subTest(mutant=name):
                self.assertGreater(kills, 0)
        self.assertGreaterEqual(killers['wa_207785393'], 20)

    def test_brute_checks(self):
        counts = recipe.brute_checks()
        self.assertEqual(set(counts), {'785C'})
        self.assertGreaterEqual(counts['785C'], 40000)

    def test_exhaustive_simulation_matches_independent_least_k(self):
        for n in range(1, 61):
            for m in range(1, 61):
                expected = n if m >= n else m + least_k(n - m)
                self.assertEqual(recipe.brute('785C', (n, m)), expected)
                self.assertEqual(recipe.answer('785C', (n, m)), expected)

    def test_extras_are_valid_distinct_and_categorized(self):
        self.assertGreaterEqual(len(self.cases), 120)
        self.assertLessEqual(len(self.cases), 180)
        self.assertEqual(len({c['input'] for c in self.cases}), len(self.cases))
        for case, (n, m) in zip(self.cases, self.parsed):
            with self.subTest(input=case['input']):
                self.assertEqual(set(case), {'input', 'output', 'reason', 'category'})
                self.assertIn(case['category'], {'boundary', 'adversarial', 'maxSize'})
                self.assertTrue(case['reason'])
                self.assertRegex(case['input'], r'^[1-9][0-9]* [1-9][0-9]*\n$')
                self.assertRegex(case['output'], r'^[1-9][0-9]*\n$')
                expected = recipe.closed_form((n, m))
                self.assertEqual(int(case['output']), expected)
                if m < n:
                    self.assertTrue(tri(expected - m) >= n - m > tri(expected - m - 1))
                if expected <= 20000:
                    self.assertEqual(recipe.brute('785C', (n, m)), expected)
        pairs = set(self.parsed)
        self.assertIn((1, 1), pairs)
        self.assertIn((LIMIT, 1), pairs)
        self.assertIn((LIMIT, LIMIT), pairs)
        self.assertIn((1, LIMIT), pairs)
        self.assertEqual({c['category'] for c in self.cases}, {'boundary', 'adversarial', 'maxSize'})

    def test_extras_deterministic_across_hash_seeds(self):
        code = 'import json,recipe_785C as r;print(json.dumps(r.extras("785C"),sort_keys=True))'
        outputs = set()
        for seed in ('0', '12345'):
            env = dict(os.environ, PYTHONHASHSEED=seed)
            outputs.add(subprocess.run([sys.executable, '-c', code], cwd=HERE, env=env, check=True,
                                       capture_output=True, text=True).stdout)
        self.assertEqual(len(outputs), 1)
        self.assertEqual(json.loads(outputs.pop()), self.cases)


